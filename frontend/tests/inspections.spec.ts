import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('inspection persists, computes incidence and updates the health map after review', async ({ page }) => {
  await page.goto('/#disease');
  await expect(page.getByRole('heading', { name: 'Inspecciones fitosanitarias' })).toBeVisible();
  await page.getByRole('button', { name: 'Nueva inspección', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', { name: 'Bloque', exact: true }).selectOption('5');
  await dialog.getByLabel('Problema sospechado').selectOption('WEEVILS');
  await dialog.getByLabel('Plantas inspeccionadas').fill('20');
  await dialog.getByLabel('Plantas afectadas').fill('5');
  await expect(dialog.getByRole('status')).toHaveText('Incidencia: 25 %');
  await dialog.getByLabel('Síntomas observados').fill('Daños de picudo para seguimiento.');
  await dialog.getByLabel('Severidad del daño (%)').fill('10');
  await dialog.getByLabel('Método de evaluación').fill('Porcentaje visual de daño del cormo.');
  await dialog.getByRole('button', { name: 'Guardar inspección', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  const record = page.locator('tbody tr').filter({ hasText: 'Picudos' });
  await expect(record).toContainText('25 %');
  await expect(record).toContainText('Sospechosa');
  await page.goto('/#maps');
  await page.getByRole('button', { name: 'Salud del cultivo', exact: true }).click();
  await page.getByRole('button', { name: 'Seleccionar Bloque E', exact: true }).click();
  await expect(page.locator('.map-popup')).toContainText('Hallazgos activos');
  await page.goto('/#disease');
  await page.locator('tbody tr').filter({ hasText: 'Picudos' }).getByRole('button').click();
  await dialog.getByLabel('Estado de evaluación').selectOption('DISCARDED');
  await dialog.getByLabel('Hallazgo resuelto').check();
  await dialog.getByLabel('Justificación de la revisión').fill('Inspección de seguimiento sin hallazgos activos.');
  await dialog.getByRole('button', { name: 'Guardar revisión' }).click();
  await expect(dialog).not.toBeVisible();
  await page.goto('/#maps');
  await page.getByRole('button', { name: 'Salud del cultivo', exact: true }).click();
  await page.getByRole('button', { name: 'Seleccionar Bloque E', exact: true }).click();
  await expect(page.locator('.map-popup')).toContainText('Sin hallazgos activos recientes');
  await page.getByRole('button', { name: 'Seleccionar Bloque C', exact: true }).click();
  await expect(page.locator('.map-popup')).toContainText('Sin evaluación reciente');
});

test('treatments, evidence, follow-ups, CSV and annulment preserve the inspection history', async ({ page }) => {
  await page.goto('/#disease');
  await page.getByRole('button', { name: 'Ver inspección 1', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'Registrar tratamiento', exact: true }).click();
  await dialog.getByLabel('Descripción del tratamiento').fill('Deshoje sanitario realizado según el plan.');
  await dialog.getByRole('button', { name: 'Guardar tratamiento', exact: true }).click();
  await expect(dialog).toContainText('Deshoje sanitario realizado según el plan.');
  await dialog.getByRole('button', { name: 'Registrar evidencia', exact: true }).click();
  await dialog.getByRole('combobox', { name: 'Asociar evidencia a' }).selectOption({ index: 1 });
  await dialog.getByLabel('Referencia S3').fill('inspecciones/deshoje.jpg');
  await dialog.getByLabel('Tipo de contenido').fill('image/jpeg');
  await dialog.getByRole('button', { name: 'Guardar evidencia', exact: true }).click();
  await expect(dialog).toContainText('inspecciones/deshoje.jpg');
  const treatmentDownloadPromise = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Exportar tratamientos CSV', exact: true }).click();
  const treatmentDownload = await treatmentDownloadPromise;
  const treatmentCsv = await readFile((await treatmentDownload.path())!, 'utf8');
  expect(treatmentCsv).toContain('Deshoje sanitario realizado según el plan.');
  expect(treatmentCsv).toContain('inspecciones/deshoje.jpg');
  await page.reload();
  await page.getByRole('button', { name: 'Ver inspección 1', exact: true }).click();
  await expect(dialog).toContainText('Deshoje sanitario realizado según el plan.');
  await expect(dialog).toContainText('inspecciones/deshoje.jpg');
  await dialog.getByRole('button', { name: 'Registrar seguimiento', exact: true }).click();
  await expect(dialog.getByRole('combobox', { name: 'Bloque', exact: true })).toBeDisabled();
  await dialog.getByLabel('Síntomas observados').fill('Sin síntomas durante el seguimiento.');
  await dialog.getByLabel('Método de evaluación').fill('Evaluación visual del área foliar.');
  await dialog.getByRole('button', { name: 'Guardar inspección', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Ver inspección 5', exact: true }).click();
  await expect(dialog).toContainText('Seguimiento de inspección #1');
  await dialog.getByRole('button', { name: 'Ver inspección de origen', exact: true }).click();
  await expect(dialog).toContainText('Ver seguimiento #5');
  await dialog.getByRole('button', { name: 'Anular inspección', exact: true }).click();
  await dialog.getByLabel('Motivo de anulación').fill('Registro duplicado, se conserva para auditoría.');
  await dialog.getByRole('button', { name: 'Confirmar anulación', exact: true }).click();
  await expect(dialog).toContainText('Anulada: Registro duplicado');
  await expect(dialog).toContainText('inspecciones/deshoje.jpg');
  await expect(dialog.getByRole('button', { name: 'Registrar tratamiento', exact: true })).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.reload();
  await expect(page.locator('tbody tr').filter({ has: page.getByRole('button', { name: 'Ver inspección 1', exact: true }) })).toContainText('Anulada');
  await page.getByRole('combobox', { name: 'Problema', exact: true }).selectOption('SIGATOKA');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar inspecciones CSV', exact: true }).click();
  const download = await downloadPromise;
  const csv = await readFile((await download.path())!, 'utf8');
  expect(csv).toContain('Registro duplicado, se conserva para auditoría.');
  expect(csv).toContain('Sigatoka negra');
  expect(csv).not.toContain('Marchitez por Fusarium');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy();
});

test('legacy observations and treatment entry remain accessible in the health workspace', async ({ page }) => {
  await page.goto('/#disease');
  await page.getByRole('button', { name: 'Historial anterior y tratamientos', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Plagas y enfermedades', exact: true })).toBeVisible();
  await expect(page.locator('tbody')).toContainText('Seguimiento de síntomas foliares');
  await expect(page.getByRole('button', { name: 'Exportar CSV', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Nueva observación', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', { name: 'Tipo de actividad' }).selectOption('TREATMENT_APPLICATION');
  await dialog.getByRole('combobox', { name: 'Bloque', exact: true }).selectOption('1');
  await dialog.getByLabel('Notas', { exact: true }).fill('Tratamiento del historial anterior.');
  await dialog.getByRole('button', { name: 'Registrar actividad', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.locator('tbody')).toContainText('Tratamiento del historial anterior.');
});
