SET MODE PostgreSQL;
CREATE DOMAIN TIMESTAMPTZ AS TIMESTAMP WITH TIME ZONE;
CREATE TABLE farm (id BIGINT PRIMARY KEY, name TEXT NOT NULL);
CREATE TABLE field (id BIGINT PRIMARY KEY, farm_id BIGINT NOT NULL REFERENCES farm(id));
CREATE TABLE block (id BIGINT PRIMARY KEY, field_id BIGINT NOT NULL REFERENCES field(id), area_ha NUMERIC(12,4), crop TEXT, variety TEXT);
CREATE TABLE row_line (id BIGINT PRIMARY KEY, block_id BIGINT NOT NULL REFERENCES block(id));
CREATE TABLE field_event (id BIGSERIAL PRIMARY KEY, event_type TEXT, occurred_at TIMESTAMPTZ, created_by_user_id BIGINT, block_id BIGINT, row_id BIGINT, notes TEXT);
